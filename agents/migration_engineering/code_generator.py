"""Code Generator for Agent 3.

Assembles modified source files, database client configuration,
and package dependencies for the PostgreSQL/Prisma target.
"""

from __future__ import annotations

import json
import re
from typing import Dict, List, Optional, Tuple


class CodeGenerator:
    def update_service_file(
        self,
        code: str,
        function_replacements: Dict[str, str],
        model_name: str,
    ) -> Tuple[str, List[str]]:
        """
        Replace Mongoose imports and function bodies with Prisma counterparts.
        Returns: (updated_file_content, list_of_changes)
        """
        changes: List[str] = []
        new_code = code
        escaped_name = re.escape(model_name)

        # 1. Replace function bodies
        for old_fn, new_fn in function_replacements.items():
            if old_fn in new_code:
                new_code = new_code.replace(old_fn, new_fn)
                changes.append("Updated function body to use Prisma")

        # 2. Replace Model import with Prisma client import
        # CommonJS: const User = require('../models/User'); -> const prisma = require('../config/prisma');
        cjs_pattern = re.compile(
            r"const\s+" + escaped_name + r"\s*=\s*require\(\s*['\"][^'\"]*models/" + escaped_name + r"(?:\.js)?['\"]\s*\);"
        )
        if cjs_pattern.search(new_code):
            if "require('../config/prisma')" not in new_code:
                new_code = cjs_pattern.sub(
                    "const prisma = require('../config/prisma');",
                    new_code,
                    count=1,
                )
                changes.append(f"Replaced {model_name} Mongoose import with Prisma client")
            else:
                new_code = cjs_pattern.sub("", new_code)

        # ESM: import Post from '../models/Post.js'; -> import prisma from '../config/prisma.js';
        esm_pattern = re.compile(
            r"import\s+" + escaped_name + r"\s+from\s+['\"][^'\"]*models/" + escaped_name + r"(?:\.js)?['\"];"
        )
        if esm_pattern.search(new_code):
            if "from '../config/prisma.js'" not in new_code:
                new_code = esm_pattern.sub(
                    "import prisma from '../config/prisma.js';",
                    new_code,
                    count=1,
                )
                changes.append(f"Replaced {model_name} ESM import with Prisma client")
            else:
                new_code = esm_pattern.sub("", new_code)

        return new_code, changes

    def generate_prisma_client_module(self, is_esm: bool = False) -> str:
        """Generate src/config/prisma.js initialization module."""
        if is_esm:
            return (
                "// Generated by MigrateAI Agent 3\n"
                "import { PrismaClient } from '@prisma/client';\n\n"
                "const prisma = new PrismaClient();\n\n"
                "export default prisma;\n"
            )
        return (
            "// Generated by MigrateAI Agent 3\n"
            "const { PrismaClient } = require('@prisma/client');\n\n"
            "const prisma = new PrismaClient();\n\n"
            "module.exports = prisma;\n"
        )

    def update_package_json(self, package_json_text: str) -> Tuple[str, List[str]]:
        """Add @prisma/client and prisma dependencies to package.json."""
        changes = []
        try:
            data = json.loads(package_json_text)
        except Exception:
            return package_json_text, changes

        deps = data.setdefault("dependencies", {})
        dev_deps = data.setdefault("devDependencies", {})

        if "@prisma/client" not in deps:
            deps["@prisma/client"] = "^5.14.0"
            changes.append("Added @prisma/client to dependencies")

        if "prisma" not in dev_deps and "prisma" not in deps:
            dev_deps["prisma"] = "^5.14.0"
            changes.append("Added prisma to devDependencies")

        return json.dumps(data, indent=2) + "\n", changes
